TEST(PathClassifierTest, GeneratedHeaderContent) {
    PathClassifier c;
    EXPECT_EQ(c.classify("internal/types/types.go",
                         "// Code generated by jsvm. DO NOT EDIT.\n"
                         "package types\n"),
              PathAttr::Generated);
    EXPECT_EQ(c.classify("internal/types/types.go", "package types\n"),
              PathAttr::Production);
}

