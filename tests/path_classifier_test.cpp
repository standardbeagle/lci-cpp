// -- Built-in defaults: Go ----------------------------------------------------

TEST(PathClassifierTest, GoTestFile) {
    PathClassifier c;
    EXPECT_EQ(c.classify("middleware/logger_test.go"), PathAttr::Test);
    EXPECT_EQ(c.classify("mux_test.go"), PathAttr::Test);
}

